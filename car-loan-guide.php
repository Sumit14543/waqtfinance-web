                   <h2>Know the Required Documents</h2>

                   <p>To apply for a car loan, lenders usually require certain documents for verification.</p>

                   <ul>
                       <li>Identity proof (Aadhaar Card, PAN Card, Passport)</li>
                       <li>Address proof</li>
                       <li>Income proof (Salary slips or Income Tax Returns)</li>
                       <li>Bank statements</li>
                       <li>Employment or business details</li>
                       <li>Vehicle quotation from the dealer</li>
                   </ul>

                   <p>Having these documents ready can speed up the loan approval process.</p>

                   <h4>Read the Loan Terms Carefully</h4>

                   <p>Before signing the loan agreement, it is important to read all the terms and conditions carefully. Pay special attention to the interest rate type, repayment schedule, penalty clauses, and foreclosure rules.</p>

                   <p>Understanding the loan agreement ensures that you are fully aware of your financial responsibilities.</p>

