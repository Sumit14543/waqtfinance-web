                <h2>What is Loan Against Property?</h2>

                <p>A Loan Against Property is a secured loan where the borrower pledges their property as collateral to get funding from a lender. The property remains in the borrower’s possession, but the lender has legal rights over it until the loan is fully repaid.</p>

                <p>Since it is a secured loan, LAP usually comes with lower interest rates compared to personal loans and offers higher loan amounts based on property value.</p>

                <h2>How Does Loan Against Property Work?</h2>

                <p>When you apply for a LAP, the bank evaluates your property value, income, credit score, and repayment capacity. Based on this assessment, the lender sanctions a loan amount, typically up to 50%–70% of the property’s market value.</p>

                <p>You repay the loan through monthly EMIs over a tenure that can range from 5 to 20 years depending on the lender’s policy.</p>

