    // --- Speedometer Animation Logic ---
    const animateSpeedometer = (score, rating) => {
        const needle = document.getElementById('gaugeNeedle');
        const path = document.getElementById('gaugePath');
        const scoreText = document.getElementById('finalScore');
        const ratingText = document.getElementById('scoreRating');
        
        // Calculation: 300 to 900
        const minScore = 300;
        const maxScore = 900;
        const percentage = Math.min(Math.max((score - minScore) / (maxScore - minScore), 0), 1);
        
        // Needle Rotation: -90deg to +90deg
        const rotation = (percentage * 180) - 90;
        needle.style.transform = `rotate(${rotation}deg)`;
        
        // Path Offset: 440 (empty) to 0 (full)
        const offset = 440 * (1 - percentage);
        path.style.strokeDashoffset = offset;
        
        // Color transition
        let color = '#c1272d'; // Poor
        if (score >= 750) color = '#27ae60'; // Excellent
        else if (score >= 700) color = '#f39c12'; // Good
        else if (score >= 650) color = '#e67e22'; // Fair
        
        path.style.stroke = color;

        // Counter Animation
        let currentDisplay = 300;
        const duration = 1500;
        const startTime = performance.now();

        const updateFrame = (now) => {
            const elapsed = now - startTime;
            const progress = Math.min(elapsed / duration, 1);
            const easedProgress = 1 - Math.pow(1 - progress, 3); // easeOutCubic
            
            currentDisplay = minScore + (score - minScore) * easedProgress;
            scoreText.textContent = Math.round(currentDisplay);
            
            if (progress < 1) {
                requestAnimationFrame(updateFrame);
            } else {
                scoreText.style.color = color;
                ratingText.textContent = rating;
                ratingText.style.color = color;
            }
        };
        requestAnimationFrame(updateFrame);
    };

    // --- Final Score Fetch ---
    const fetchScore = async () => {
        document.querySelectorAll('.form-step').forEach(s => s.classList.remove('active'));
        document.getElementById('loadingStep').classList.add('active');
        document.querySelector('.progress-container').style.display = 'none';

        const formData = new FormData(form);
        const showScoreError = (message) => {
            document.getElementById('loadingStep').classList.remove('active');
            document.getElementById('resultStep').classList.add('active');
            document.getElementById('scoreMessage').textContent = "Error: " + message;
            document.getElementById('scoreMessage').style.color = 'var(--primary-red)';
            document.querySelector('.speedometer-container').style.display = 'none';
            document.getElementById('downloadReport').style.display = 'none';
        };

        try {
            const data = await apiRequest('api/score.php', formData);

            const score = Number(data.score);
            const hasValidScore = Number.isInteger(score) && score >= 300 && score <= 900;

            if (!hasValidScore && !data.pdf_url) {
                showScoreError('Credit report URL was not available in the bureau response. Please try again later.');
                return;
            }

            document.getElementById('loadingStep').classList.remove('active');
            document.getElementById('resultStep').classList.add('active');
            document.querySelector('.speedometer-container').style.display = hasValidScore ? 'block' : 'none';
            document.getElementById('downloadReport').style.display = 'flex';
            document.getElementById('scoreMessage').textContent = data.message || 'Your CIBIL report is ready. Download the PDF to view your score and full bureau details.';
            document.getElementById('scoreMessage').style.color = '';

            if (hasValidScore) {
                animateSpeedometer(score, data.rating || 'Good');
            }
            lastReportData = data;

            const downloadBtn = document.getElementById('downloadReport');
            if (data.pdf_url) {
                downloadBtn.href = data.pdf_url;
                downloadBtn.onclick = null;
                downloadBtn.setAttribute('target', '_blank');
            } else {
                downloadBtn.href = "javascript:void(0)";
                downloadBtn.onclick = () => generateProfessionalPDF(data);
            }
            downloadBtn.innerHTML = '<i class="fas fa-file-download"></i> Download Report';
        } catch (error) {
            console.error('Credit score fetch failed:', error);
            showScoreError(error.message || 'Unable to fetch your report right now. Please try again.');
        }
    };

