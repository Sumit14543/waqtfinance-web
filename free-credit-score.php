    document.addEventListener('DOMContentLoaded', () => {
    const form = document.getElementById('cibilForm');
    const steps = document.querySelectorAll('.form-step');
    const indicators = document.querySelectorAll('.step-indicator');
    const nextBtns = document.querySelectorAll('.next-step');
    const prevBtns = document.querySelectorAll('.prev-step');
    let currentStep = 1;
    let lastReportData = null; // Store API response for PDF generation
    const csrfToken = window.WAQT_CSRF_TOKEN || document.querySelector('meta[name="csrf-token"]')?.content || '';

    const appendCsrf = (formData) => {
        if (csrfToken && !formData.has('csrf_token')) {
            formData.append('csrf_token', csrfToken);
        }
        return formData;
    };

    const apiRequest = async (url, formData) => {
        const response = await fetch(url, {
            method: 'POST',
            headers: { 'X-CSRF-Token': csrfToken },
            body: appendCsrf(formData)
        });
        const rawText = await response.text();
        let data = {};

        if (rawText) {
            try {
                data = JSON.parse(rawText);
            } catch (error) {
                const fallbackMessage = response.ok
                    ? 'Server returned an invalid response. Please try again.'
                    : 'Server error. Please try again later.';
                data = { status: 'error', message: fallbackMessage };
                console.error('Invalid API response from ' + url, rawText);
            }
        }

        if (!response.ok || data.status === 'error') {
            throw new Error(data.message || 'Request failed. Please try again.');
        }

        return data;
    };

    // --- Step Navigation ---
    const showStep = (stepNumber) => {
        steps.forEach(step => step.classList.remove('active'));
        document.getElementById(`step${stepNumber}`).classList.add('active');
        
        indicators.forEach((ind, index) => {
            if (index + 1 === stepNumber) {
                ind.classList.add('active');
                ind.classList.remove('completed');
            } else if (index + 1 < stepNumber) {
                ind.classList.add('completed');
                ind.classList.remove('active');
            } else {
                ind.classList.remove('active', 'completed');
            }
        });
        currentStep = stepNumber;
    };

    nextBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            const nextStep = parseInt(btn.getAttribute('data-next'));
            if (validateStep(currentStep)) {
                if (btn.id === 'submitDetails') {
                    startOtpProcess();
                } else {
                    showStep(nextStep);
                }
            }
        });
    });

    prevBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            const prevStep = parseInt(btn.getAttribute('data-prev'));
            showStep(prevStep);
        });
    });

    // --- Validation ---
    const validateStep = (step) => {
        let isValid = true;
        const currentFields = document.getElementById(`step${step}`).querySelectorAll('input[required], select[required]');
        
        currentFields.forEach(field => {
            if ((field.type === 'checkbox' && !field.checked) || (field.type !== 'checkbox' && !field.value.trim())) {
                markInvalid(field, getRequiredMessage(field));
                isValid = false;
            } else {
                clearInvalid(field);
                
                if (field.id === 'pan' && !/^[A-Z]{5}[0-9]{4}[A-Z]{1}$/.test(field.value.toUpperCase())) {
                    markInvalid(field, 'Enter a valid PAN number, for example ABCDE1234F.');
                    isValid = false;
                }
                if (field.id === 'aadhaar' && !/^[0-9]{12}$/.test(field.value.replace(/\s/g, ''))) {
                    markInvalid(field, 'Enter a valid 12-digit Aadhaar number.');
                    isValid = false;
                }
                if (field.id === 'mobile' && !/^[6-9][0-9]{9}$/.test(field.value.replace(/\D/g, ''))) {
                    markInvalid(field, 'Enter a valid 10-digit Indian mobile number.');
                    isValid = false;
                }
                if (field.id === 'email' && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(field.value)) {
                    markInvalid(field, 'Enter a valid email address for OTP verification.');
                    isValid = false;
                }
            }
        });
        return isValid;
    };

    const getRequiredMessage = (field) => {
        const messages = {
            first_name: 'Enter your first name as per your documents.',
            last_name: 'Enter your last name as per your documents.',
            mobile: 'Enter your mobile number linked with bank or Aadhaar.',
            email: 'Enter your email address to receive OTP.',
            pan: 'Enter your PAN number.',
            aadhaar: 'Enter your 12-digit Aadhaar number.',
            consent: 'Please accept the consent to fetch your credit report.'
        };

        return messages[field.id] || messages[field.name] || 'Please complete this field.';
    };

    const markInvalid = (field, msg) => {
