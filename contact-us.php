<script>
    function handlePhoneInput(e) {
        let value = e.target.value;

        value = value.replace(/\D/g, "");
        if (value.length > 10) {
            value = value.slice(0, 10);
        }

        e.target.value = value;
    }
    document.getElementById("phone").addEventListener("input", handlePhoneInput);

    const form = document.getElementById("contactForm");
    const successMessage = document.getElementById("successMessage");

    const fields = {
        name: {
            el: document.getElementById("name"),
            validate: v => v.trim().length >= 3 || "Name must be at least 3 characters"
        },
        email: {
            el: document.getElementById("email"),
            validate: v =>
                /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v) || "Enter a valid email address"
        },
        phone: {
            el: document.getElementById("phone"),
            validate: v =>
                /^\d{10}$/.test(v) || "Phone must be 10 digits"
        },
        subject: {
            el: document.getElementById("subject"),
            validate: v => v !== "" || "Please select a subject"
        },
        message: {
            el: document.getElementById("message"),
            validate: v =>
                v.trim().length >= 10 || "Message must be at least 10 characters"
        },
        consent: {
            el: document.getElementById("consent"),
            validate: v => v === true || "You must accept the privacy policy"
        }
    };

    function getErrorEl(field) {
        const container = field.el.closest(".col-sm-6, .mb-3, .form-group");
        if (container) {
            return container.querySelector(".error-text");
        }
        return field.el.parentElement.querySelector(".error-text");
    }

    function showError(field, message) {
        const errorEl = getErrorEl(field);
        if (errorEl) {
            errorEl.textContent = message;
        }
        field.el.classList.add("error");
    }

    function clearError(field) {
        const errorEl = getErrorEl(field);
        if (errorEl) {
            errorEl.textContent = "";
        }
        field.el.classList.remove("error");
    }

    /* ===== SUBMIT HANDLER ===== */
    form.addEventListener("submit", async function(e) {
        e.preventDefault();

        let isValid = true;

        Object.values(fields).forEach(field => {
            const value = field.el.type === "checkbox" ?
                field.el.checked :
                field.el.value;

            const result = field.validate(value);

            if (result !== true) {
                showError(field, result);
                isValid = false;
            } else {
                clearError(field);
            }
        });

        if (!isValid) return;

        const formData = new FormData(form);
        const submitBtn = form.querySelector("button[type='submit']");
        const originalBtnContent = submitBtn.innerHTML;

        submitBtn.disabled = true;
        submitBtn.innerHTML = 'Sending... <i class="fa-solid fa-spinner fa-spin ms-2 mt-1"></i>';

        try {
            const response = await fetch("form-actions/submit-contact", {
                method: "POST",
                headers: {
                    "X-CSRF-Token": window.WAQT_CSRF_TOKEN || ""
                },
                body: formData
            });

            const data = await response.json();

            if (data.success) {
                Swal.fire({
                    icon: "success",
                    title: "Message Sent!",
                    text: "We will contact you within 24 hours.",
                    confirmButtonColor: "#18529c"
                }).then(() => {
                    window.location.href = "thanks?type=contact";
                });

            } else {
                Swal.fire({
                    icon: "error",
                    title: "Submission Failed",
                    text: data.message || "Something went wrong!"
                });
                submitBtn.disabled = false;
                submitBtn.innerHTML = originalBtnContent;
            }

        } catch (err) {
            Swal.fire({
                icon: "error",
                title: "Server Error",
                text: "Please try again later."
            });
            submitBtn.disabled = false;
            submitBtn.innerHTML = originalBtnContent;
        }
    });
</script>
